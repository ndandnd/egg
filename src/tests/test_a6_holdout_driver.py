def test_selection_rejects_wrong_hash_and_internal_decision():
    path = holdout.REPO_DIR / holdout.SELECTION_RELATIVE_PATH
    payload = json.loads(path.read_text())
    with pytest.raises(holdout.HoldoutGuardError, match="SHA-256"):
        holdout._validate_selection_payload(
            payload, "0" * 64
        )
    changed = copy.deepcopy(payload)
    changed["selected_arm"] = "a6_a3"
    with pytest.raises(holdout.HoldoutGuardError, match="frozen decision"):
        holdout._validate_selection_payload(
            changed, holdout.EXPECTED_SELECTION_SHA256
        )
    changed = copy.deepcopy(payload)
    changed["matched"][0]["a6_a3_wins"] = not changed["matched"][0][
        "a6_a3_wins"
    ]
    with pytest.raises(holdout.HoldoutGuardError, match="reproduce"):
        holdout._validate_selection_payload(
            changed, holdout.EXPECTED_SELECTION_SHA256
        )


