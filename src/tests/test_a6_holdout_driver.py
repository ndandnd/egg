def test_launcher_functionally_refuses_main_origin_mismatch(tmp_path):
    """Exercise the production shell's unpublished-HEAD refusal without
    reaching Gurobi, feasibility generation, or sbatch."""
    cluster = tmp_path / "repo" / "src" / "cluster"
    cluster.mkdir(parents=True)
    launcher = cluster / "launch_a6_holdout.sh"
    launcher.write_text(
        (holdout.SRC_DIR / "cluster/launch_a6_holdout.sh").read_text()
    )
    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    git = fake_bin / "git"
    git.write_text("""#!/bin/sh
case "$*" in
  *"status --porcelain --untracked-files=no"*) exit 0 ;;
  *"symbolic-ref --quiet --short HEAD"*) echo main ;;
  *"rev-parse HEAD"*) echo aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa ;;
  *"rev-parse refs/remotes/origin/main"*) echo bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb ;;
  *) echo "unexpected fake git call: $*" >&2; exit 99 ;;
esac
""")
    sbatch = fake_bin / "sbatch"
    sbatch.write_text("#!/bin/sh\necho 'sbatch must not run' >&2\nexit 88\n")
    git.chmod(0o755)
    sbatch.chmod(0o755)
    env = dict(os.environ)
    env["PATH"] = f"{fake_bin}:{env['PATH']}"
    proc = subprocess.run(
        ["bash", str(launcher)], text=True, capture_output=True, env=env
    )
    assert proc.returncode == 1
    assert "!= local origin/main" in proc.stderr
    assert "git pull --ff-only origin main" in proc.stderr
    assert "sbatch must not run" not in proc.stderr


def _fake_happy_launcher_repo(tmp_path):
    """Minimal fake Unicorn/repository contract that reaches sbatch without
    importing project code or generating scientific outcomes."""
    repo = tmp_path / "repo"
    src = repo / "src"
    cluster = src / "cluster"
    experiments = src / "experiments"
    cluster.mkdir(parents=True)
    experiments.mkdir()
    launcher = cluster / "launch_a6_holdout.sh"
    launcher.write_text(
        (holdout.SRC_DIR / "cluster/launch_a6_holdout.sh").read_text()
    )
    (cluster / "unicorn_env.sh").write_text(":\n")

    selection = repo / holdout.SELECTION_RELATIVE_PATH
    selection.parent.mkdir(parents=True)
    selection.write_bytes(
        (holdout.REPO_DIR / holdout.SELECTION_RELATIVE_PATH).read_bytes()
    )
    fake_driver = experiments / "run_a6_holdout.py"
    fake_driver.write_text("""#!/usr/bin/env python3
import json
from pathlib import Path
import sys

if "--preflight" in sys.argv:
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    out.mkdir(parents=True, exist_ok=True)
    (out / "PREFLIGHT.json").write_text(json.dumps({"ok": True}) + "\\n")
elif "--list" in sys.argv:
    print("selection:", {"selected_arm": "a6_a4"})
    k = 0
    for method in ("a2", "a6_a4"):
        for seed in range(16, 32):
            for n in (8, 12):
                for b in (0.01, 0.05):
                    print(k, {"method": method, "seed": seed,
                              "n_trips": n, "b": b,
                              "epsilon": 0.01, "budget": 240})
                    k += 1
    print(f"total: {k} cells")
else:
    raise SystemExit(91)
""")

    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    code_commit = "c" * 40
    git = fake_bin / "git"
    git.write_text(f"""#!/bin/sh
case "$*" in
  *"status --porcelain --untracked-files=no"*) exit 0 ;;
  *"symbolic-ref --quiet --short HEAD"*) echo main ;;
  *"rev-parse refs/remotes/origin/main"*) echo {code_commit} ;;
  *"rev-parse HEAD"*) echo {code_commit} ;;
  *"merge-base --is-ancestor"*) exit 0 ;;
  *"ls-files --error-unmatch"*) exit 0 ;;
  *) echo "unexpected fake git call: $*" >&2; exit 99 ;;
esac
""")
    counter = tmp_path / "sbatch.calls"
    sbatch = fake_bin / "sbatch"
    sbatch.write_text("""#!/bin/sh
printf 'call\\n' >> "$FAKE_SBATCH_COUNTER"
echo 424242
""")
    squeue = fake_bin / "squeue"
    squeue.write_text("#!/bin/sh\nexit 0\n")
    for exe in (git, sbatch, squeue):
        exe.chmod(0o755)
    os.symlink(sys.executable, fake_bin / "python")
    env = dict(os.environ)
    env["PATH"] = f"{fake_bin}:{env['PATH']}"
    env["FAKE_SBATCH_COUNTER"] = str(counter)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return launcher, src, env, counter


def test_launcher_one_shot_lock_allows_first_and_refuses_second(tmp_path):
    launcher, src, env, counter = _fake_happy_launcher_repo(tmp_path)
    first = subprocess.run(
        ["bash", str(launcher)], cwd=src, text=True,
        capture_output=True, env=env,
    )
    assert first.returncode == 0, first.stderr
    assert counter.read_text().splitlines() == ["call"]
    lock = src / "runs/a6_holdout/SUBMISSION_LOCK"
    assert (lock / "CLAIM.txt").is_file()
    assert (lock / "INTENT.txt").is_file()
    assert (lock / "SUBMITTED.txt").is_file()

    second = subprocess.run(
        ["bash", str(launcher)], cwd=src, text=True,
        capture_output=True, env=env,
    )
    assert second.returncode == 1
    assert "sentinel" in second.stderr
    assert counter.read_text().splitlines() == ["call"]


@pytest.mark.parametrize("checkpoint_name", [
    "a2.cg.ckpt.json", "dictator.ckpt.json",
])
def test_launcher_refuses_preexisting_checkpoint_before_lock_or_sbatch(
    tmp_path, checkpoint_name,
):
    launcher, src, env, counter = _fake_happy_launcher_repo(tmp_path)
    stale = src / f"runs/a6_holdout/a2_s16_n8_b0.01/{checkpoint_name}"
