def test_preflight_is_atomic_deterministic_and_tamper_refusing(tmp_path):
    selection = holdout.load_committed_selection()
    root = str(tmp_path / "runs")
    first = holdout.write_preflight(root, selection, "code-test")
    path = tmp_path / "runs" / holdout.PREFLIGHT_FILENAME
    assert json.loads(path.read_text()) == first
    second = holdout.write_preflight(root, selection, "code-test")
    assert second == first
    observed, digest = holdout.load_valid_preflight(
        root, selection, "code-test"
    )
    assert observed == first and len(digest) == 64
    tampered = copy.deepcopy(first)
    tampered["physical_instances"].pop()
    checkpoint.save(str(path), tampered)
    with pytest.raises(holdout.HoldoutGuardError, match="tampered"):
        holdout.load_valid_preflight(root, selection, "code-test")


