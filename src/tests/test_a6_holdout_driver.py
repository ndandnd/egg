def test_dispatches_fresh_a2_and_a6_a4_with_truthful_lineage(
    tmp_path, monkeypatch
):
    selection = holdout.load_committed_selection()
    gate = {
        "selection": selection,
        "code_commit": "implementation-commit",
        "preflight_sha256": "f" * 64,
    }
    args = SimpleNamespace(out=str(tmp_path), mip_gap=1e-6)
    dictator_calls = []
    a2_calls = []
    a6_calls = []

    def fake_dictator(inst, market, out, tag, cell, kw, *, experiment):
        dictator_calls.append((tag, tuple(cell), experiment))
        return {"z_d_ub": 1.0, "tol_d": 1e-2}

    monkeypatch.setattr(holdout, "_dictator_stage", fake_dictator)
    monkeypatch.setattr(
        holdout, "certified_cg",
        lambda *a, **kw: a2_calls.append(kw) or _fake_state(),
    )
    monkeypatch.setattr(
        holdout, "certified_cg_a6",
        lambda *a, **kw: a6_calls.append(kw) or _fake_state(),
    )

    a2 = ("a2", 16, 8, 0.01)
    a6 = ("a6_a4", 16, 8, 0.01)
    # A valid budget-exhausted outcome returns normally: certification is an
    # endpoint, not a per-cell completeness exception.
    holdout.run_cell(a2, args, gate=gate)
    holdout.run_cell(a6, args, gate=gate)

    assert [c[2] for c in dictator_calls] == ["a6-holdout", "a6-holdout"]
    assert a2_calls[0]["method"] == "a2"
    assert a2_calls[0]["experiment"] == "a6-holdout"
    assert a6_calls[0]["method"] == "a6_a4"
    assert a6_calls[0]["experiment"] == "a6-holdout"
    assert not any(kw.get("method") == "a6_a3" for kw in a6_calls)
    for cell in (a2, a6):
        p = tmp_path / holdout._cell_tag(cell) / \
            holdout.CELL_PROVENANCE_FILENAME
        x = json.loads(p.read_text())
        assert x["campaign"] == "a6-holdout"
        assert x["preflight_sha256"] == "f" * 64
        assert x["selection"]["selected_arm"] == "a6_a4"


def test_dictator_helper_labels_record_and_versions_representation_identity(
    tmp_path, monkeypatch
):
    """Campaign lineage and representation policy are both checkpointed."""
    inst = synthetic_instance(seed=16, n_trips=8)
    market = make_affine_market(inst, shape="duck", b_scale=0.01)
    stats = SimpleNamespace(
        extra={"adaptive_converged": True, "adaptive_gap_abs": 0.0,
               "adaptive_tol_abs": 1e-2, "adaptive_lb": 1.0},
        status="OPTIMAL", bound=0.0,
    )
    sol = SimpleNamespace(
        stats=stats, obj_true=1.0, obj_model=1.0, ops_cost=1.0,
        load=[0.0] * inst.n_slots, charges=[], energy_charged_kwh=0.0)
    seen = {}
    monkeypatch.setattr(dictator_driver, "backend", lambda: "GRB")
    monkeypatch.setattr(
        dictator_driver, "solve_dictator", lambda *a, **kw: sol
    )

    def fake_record(experiment, *args, **kwargs):
        seen["experiment"] = experiment
        return {"replay_ok": True, "experiment": experiment}

    monkeypatch.setattr(dictator_driver, "make_record", fake_record)
    state = dictator_driver._dictator_stage(
        inst, market, str(tmp_path), "tag", ["a2", 16, 8, 0.01],
        {"max_mip_gap": 1e-6, "time_limit_s": None},
        experiment="a6-holdout",
    )
    assert seen["experiment"] == "a6-holdout"
    assert state["record"]["experiment"] == "a6-holdout"
    assert "experiment" not in state["identity"]
    assert state["identity"]["load_reconstruction"] == {
        "policy_version": 1,
        "tolerance_kwh": pytest.approx(1e-4),
    }
    with pytest.raises(RuntimeError, match="record experiment"):
        dictator_driver._dictator_stage(
            inst, market, str(tmp_path), "tag",
            ["a2", 16, 8, 0.01],
            {"max_mip_gap": 1e-6, "time_limit_s": None},
            experiment="b2a2-pilot",
        )


